package com.artoria.repoagentbackend.repair;

import java.time.Instant;
import java.util.UUID;

public record RepairTaskResponse(
        UUID id,
        UUID issueId,
        String baseSha,
        String branchName,
        RepairTaskStatus status,
        String patchSummary,
        String patchArtifactPath,
        String validationSummary,
        String prUrl,
        BenchmarkEvaluationStatus evaluationStatus,
        Integer failToPassPassed,
        Integer failToPassFailed,
        Integer passToPassPassed,
        Integer passToPassFailed,
        String evaluationSummary,
        String harnessLogPath,
        Instant evaluatedAt,
        UUID parentTaskId,
        int attemptNumber,
        String modelName,
        String runKey,
        String errorCode,
        String errorSummary,
        Boolean retryable,
        Instant cancelRequestedAt,
        String workerId,
        Instant leaseExpiresAt,
        Instant lastHeartbeatAt,
        Long durationMs,
        Long promptTokens,
        Long completionTokens,
        Long totalTokens,
        String currentStage,
        String currentMessage,
        RepairPipelineStage pipelineStage,
        RepairWorkflowStatus workflowStatus,
        RepairPipelineStage currentPipelineStage,
        RepairStageStatus stageStatus,
        long stageSequence,
        long leaseEpoch,
        Instant admittedAt,
        int correctionAttempt,
        int maxCorrectionAttempts,
        RepairResultStatus resultStatus,
        long version,
        Instant createdAt,
        Instant completedAt
) {
    static RepairTaskResponse from(RepairTask task) {
        return new RepairTaskResponse(
                task.getId(),
                task.getIssue().getId(),
                task.getBaseSha(),
                task.getBranchName(),
                task.getStatus(),
                task.getPatchSummary(),
                task.getPatchArtifactPath(),
                task.getValidationSummary(),
                task.getPrUrl(),
                task.getEvaluationStatus(),
                task.getFailToPassPassed(),
                task.getFailToPassFailed(),
                task.getPassToPassPassed(),
                task.getPassToPassFailed(),
                task.getEvaluationSummary(),
                task.getHarnessLogPath(),
                task.getEvaluatedAt(),
                task.getParentTaskId(),
                task.getAttemptNumber(),
                task.getModelName(),
                task.getRunKey(),
                task.getErrorCode(),
                task.getErrorSummary(),
                task.getRetryable(),
                task.getCancelRequestedAt(),
                task.getWorkerId(),
                task.getLeaseExpiresAt(),
                task.getLastHeartbeatAt(),
                task.getDurationMs(),
                task.getPromptTokens(),
                task.getCompletionTokens(),
                task.getTotalTokens(),
                task.getCurrentStage(),
                task.getCurrentMessage(),
                task.getPipelineStage(),
                task.getWorkflowStatus(),
                task.getCurrentPipelineStage(),
                task.getStageStatus(),
                task.getStageSequence(),
                task.getLeaseEpoch(),
                task.getAdmittedAt(),
                task.getCorrectionAttempt(),
                task.getMaxCorrectionAttempts(),
                task.getResultStatus(),
                task.getVersion(),
                task.getCreatedAt(),
                task.getCompletedAt()
        );
    }
}
